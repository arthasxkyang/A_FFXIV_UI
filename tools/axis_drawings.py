def contours(font,char):
    gs=font.getGlyphSet(); p=RecordingPen();gs[font.getBestCmap()[ord(char)]].draw(p)
    parts=[];current=RecordingPen()
    for op,args in p.value:
        getattr(current,op)(*args)
        if op in ('closePath','endPath'):
            parts.append(current);current=RecordingPen()
    return parts


def fit(record,box,pen):
    from axis_outline_geometry import compensated_fit
    compensated_fit(record,box,pen)


def stroke(points,box,pen,width=78):
    # 等宽黑体笔画；折点使用斜接，端部平切，不引入圆头手写风格。
    l,t,r,b=box;pts=[(l+x*(r-l)/1000,850-t-y*(b-t)/1000) for x,y in points]
    # 局部部件不随盒宽直接压薄：取两个缩放量的几何平均。
    w=68*min(1,(min(r-l,b-t)/450)**.2)/2
    normals=[]
    for a,z in zip(pts,pts[1:]):
        dx,dy=z[0]-a[0],z[1]-a[1];length=math.hypot(dx,dy);normals.append((-dy/length,dx/length))
    left=[];right=[]
    for i,p in enumerate(pts):
        if i==0:n=normals[0];scale=w
        elif i==len(pts)-1:n=normals[-1];scale=w
        else:
            a,z=normals[i-1],normals[i];n=(a[0]+z[0],a[1]+z[1]);length=math.hypot(*n)
            if length<1e-6:n=z;scale=w
            else:
                n=(n[0]/length,n[1]/length);scale=min(w/max(.25,n[0]*z[0]+n[1]*z[1]),w*3)
        left.append((p[0]+n[0]*scale,p[1]+n[1]*scale));right.append((p[0]-n[0]*scale,p[1]-n[1]*scale))
    polygon=left+right[::-1]
    area=sum(a[0]*z[1]-z[0]*a[1] for a,z in zip(polygon,polygon[1:]+polygon[:1]))
    if area<0:polygon.reverse()
    pen.moveTo(polygon[0])
    for point in polygon[1:]:pen.lineTo(point)
    pen.closePath()


def draw(font,char,pen,box=(0,0,1000,1000),stack=()):
    if char in stack:raise ValueError('递归部件: '+char)
    # 自身手绘字与独立配方同名时，手绘优先。
    if char in STROKES:
        for points in STROKES[char]:stroke(points,box,pen)
    elif char in COMPOSITES or char in RECIPES:
        l,t,r,b=box
        for part,coords in (COMPOSITES.get(char) or RECIPES[char]):
            x,y,z,w=coords
            draw(font,part,pen,(l+x*(r-l)/1000,t+y*(b-t)/1000,l+z*(r-l)/1000,t+w*(b-t)/1000),stack+(char,))
    else:
        donor,indices=PARTS.get(char,(char,None));parts=contours(font,donor);record=RecordingPen()
        for i in (indices if indices is not None else range(len(parts))):parts[i].replay(record)
        fit(record,box,pen)
